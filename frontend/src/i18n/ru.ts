/** English has only the _one/_other plural forms; Russian also needs _few/_many. */
type Shape<T> = {
  [K in keyof T as K extends `${string}_few` | `${string}_many` ? never : K]: T[K] extends string ? string : Shape<T[K]>
}

export default ru
export type Messages = Shape<typeof ru>
